def _inputs():
    rng = np.random.default_rng(3)
    n, m, N = 14, 30, 12
    H = rng.normal(size=(m, n)) / np.sqrt(n)
    ens = rng.normal(size=(n, N))
    param = 0.4 + 0.05 * rng.normal(size=(2, N))
    y = H @ rng.normal(size=n) + 0.2 * rng.normal(size=m)
    R = np.diag(rng.uniform(0.05, 0.2, m))
    return y, R, param, ens, H @ ens, rng.uniform(0, 1, (n, m))


def _norms(out):
    return [[list(np.asarray(x).shape), float(np.linalg.norm(np.asarray(x, float)))]
            for x in (out if isinstance(out, (list, tuple)) else [out])]


def _check(key, out):
    got, ref = _norms(out), GOLDEN[key]
    assert [g[0] for g in got] == [r[0] for r in ref], "shapes changed"
    np.testing.assert_allclose([g[1] for g in got], [r[1] for r in ref], rtol=1e-9, atol=1e-12)


@pytest.mark.parametrize("sakov, perturb", itertools.product([False, True], [False, True]))
def test_enkf_analysis_and_localized(sakov, perturb):
    y, R, param, ens, pred, L = _inputs()
    np.random.seed(11)
    _check(f"enkf_analysis|{sakov}|{perturb}",
           enkf.enkf_analysis(y, R, param, ens, pred, Sakov=sakov, perturb_obs=perturb))
    np.random.seed(11)
    _check(f"localized|{sakov}|{perturb}",
           enkf.enkf_analysis_localized_with_inflation(
               y, R, ens, param, pred, L, Sakov=sakov, inflate_states=1.1, inflate_params=1.05,
               jitter_params=0.01, perturb_obs=perturb))


@pytest.mark.parametrize("sakov, alpha", itertools.product([False, True], [1.0, 1.3]))
def test_inflation_filters(sakov, alpha):
    y, R, param, ens, pred, _ = _inputs()
    np.random.seed(11)
    _check(f"inflation|{sakov}|{alpha}",
           enkf.enkf_analysis_inflation(y, R, param, ens, pred, Sakov=sakov, alpha=alpha))
    np.random.seed(11)
    _check(f"multiparm|{sakov}|{alpha}",
           enkf.enkf_analysis_inflation_multiparm(y, R, param, ens, pred, Sakov=sakov, alpha=alpha))


def test_dual_analysis():
    y, R, param, ens, pred, _ = _inputs()
    np.random.seed(11)
    _check("dual|True", enkf.enkf_dual_analysis(y, R, param, ens, pred, Sakov=True))
